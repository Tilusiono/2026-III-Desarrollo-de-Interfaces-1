
SET @OLD_FOREIGN_KEY_CHECKS=@@FOREIGN_KEY_CHECKS, FOREIGN_KEY_CHECKS=0;

CREATE TABLE IF NOT EXISTS DETALLE_VENTA
(
  ID_VENTA    INT           NOT NULL,
  ID_PRO      INT           NOT NULL,
  CANTIDAD    INT           NOT NULL,
  PRECIO      DECIMAL(12,2) NOT NULL,
  DESCUENTO   DECIMAL(12,2) NOT NULL DEFAULT 0,
  IMPORTE     DECIMAL(12,2) NULL    ,
  OBSERVACION VARCHAR(500)  NULL    ,
  PRIMARY KEY (ID_VENTA, ID_PRO),
  CONSTRAINT FK_VENTA_TO_DETALLE_VENTA
    FOREIGN KEY (ID_VENTA)
    REFERENCES VENTA (ID_VENTA)
    ON DELETE RESTRICT
    ON UPDATE RESTRICT,
  CONSTRAINT FK_PRODUCTO_TO_DETALLE_VENTA
    FOREIGN KEY (ID_PRO)
    REFERENCES PRODUCTO (PRO)
    ON DELETE RESTRICT
    ON UPDATE RESTRICT
);

CREATE TABLE IF NOT EXISTS PRODUCTO
(
  PRO          INT           NULL     AUTO_INCREMENT,
  NOM          VARCHAR(100)  NOT NULL,
  PREC         DECIMAL(12,2) NOT NULL,
  DESCRIPCION  VARCHAR(500)  NULL    ,
  STOCK        INT           NOT NULL DEFAULT 0,
  PESO_KG      DOUBLE        NULL    ,
  CALIFICACION FLOAT         NULL    ,
  ACTIVO       BOOLEAN       NOT NULL DEFAULT TRUE,
  FOTO_URL     VARCHAR(500)  NULL    ,
  PRIMARY KEY (PRO)
);

CREATE TABLE IF NOT EXISTS USUARIO
(
  COD_USU          INT          NULL     AUTO_INCREMENT,
  NOM              VARCHAR(100) NOT NULL,
  APE              VARCHAR(100) NOT NULL,
  CORREO           VARCHAR(150) NOT NULL,
  FECHA_NACIMIENTO DATE         NULL    ,
  ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
  FECHA_REGISTRO   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (COD_USU),
  CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO)
);

CREATE TABLE IF NOT EXISTS VENTA
(
  ID_VENTA    INT           NULL     AUTO_INCREMENT,
  FECHA       DATE          NOT NULL,
  COD_USU     INT           NOT NULL,
  TOTAL       DECIMAL(12,2) NOT NULL DEFAULT 0,
  HORA        TIME          NOT NULL,
  SUBTOTAL    DECIMAL(12,2) NOT NULL DEFAULT 0,
  DESCUENTO   DECIMAL(12,2) NOT NULL DEFAULT 0,
  IMPUESTO    DECIMAL(12,2) NOT NULL DEFAULT 0,
  ESTADO      VARCHAR(20)   NOT NULL DEFAULT 'REGISTRADA',
  OBSERVACION VARCHAR(500)  NULL    ,
  PRIMARY KEY (ID_VENTA),
  INDEX IDX_VENTA_FECHA (FECHA ASC),
  CONSTRAINT FK_USUARIO_TO_VENTA
    FOREIGN KEY (COD_USU)
    REFERENCES USUARIO (COD_USU)
    ON DELETE RESTRICT
    ON UPDATE RESTRICT
);

