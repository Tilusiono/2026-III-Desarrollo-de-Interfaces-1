
CREATE TABLE DETALLE_VENTA
(
  ID_VENTA    INT           NOT NULL,
  ID_PRO      INT           NOT NULL,
  CANTIDAD    INT           NOT NULL,
  PRECIO      DECIMAL(12,2) NOT NULL,
  DESCUENTO   DECIMAL(12,2) DEFAULT 0 NOT NULL,
  IMPORTE     DECIMAL(12,2),
  OBSERVACION VARCHAR(500) ,
  CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_VENTA, ID_PRO)
);

CREATE TABLE PRODUCTO
(
  PRO          INT          ,
  NOM          VARCHAR(100)  NOT NULL,
  PREC         DECIMAL(12,2) NOT NULL,
  DESCRIPCION  VARCHAR(500) ,
  STOCK        INT           DEFAULT 0 NOT NULL,
  PESO_KG      DOUBLE       ,
  CALIFICACION FLOAT        ,
  ACTIVO       BOOLEAN       DEFAULT TRUE NOT NULL,
  FOTO_URL     VARCHAR(500) ,
  CONSTRAINT PK_PRODUCTO PRIMARY KEY (PRO)
);

CREATE SEQUENCE SEQ_PRODUCTO
START WITH 1
INCREMENT BY 1;

CREATE OR REPLACE TRIGGER SEQ_TRG_PRODUCTO
BEFORE INSERT ON PRODUCTO
REFERENCING NEW AS NEW FOR EACH ROW
BEGIN
  SELECT SEQ_PRODUCTO.NEXTVAL
  INTO :NEW.PRO
  FROM DUAL;
END;
/

CREATE TABLE USUARIO
(
  COD_USU          INT         ,
  NOM              VARCHAR(100) NOT NULL,
  APE              VARCHAR(100) NOT NULL,
  CORREO           VARCHAR(150) NOT NULL,
  FECHA_NACIMIENTO DATE        ,
  ACTIVO           BOOLEAN      DEFAULT TRUE NOT NULL,
  FECHA_REGISTRO   DATETIME     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_USUARIO PRIMARY KEY (COD_USU)
);

ALTER TABLE USUARIO
  ADD CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO);

CREATE SEQUENCE SEQ_USUARIO
START WITH 1
INCREMENT BY 1;

CREATE OR REPLACE TRIGGER SEQ_TRG_USUARIO
BEFORE INSERT ON USUARIO
REFERENCING NEW AS NEW FOR EACH ROW
BEGIN
  SELECT SEQ_USUARIO.NEXTVAL
  INTO :NEW.COD_USU
  FROM DUAL;
END;
/

CREATE TABLE VENTA
(
  ID_VENTA    INT          ,
  FECHA       DATE          NOT NULL,
  COD_USU     INT           NOT NULL,
  TOTAL       DECIMAL(12,2) DEFAULT 0 NOT NULL,
  HORA        TIME          NOT NULL,
  SUBTOTAL    DECIMAL(12,2) DEFAULT 0 NOT NULL,
  DESCUENTO   DECIMAL(12,2) DEFAULT 0 NOT NULL,
  IMPUESTO    DECIMAL(12,2) DEFAULT 0 NOT NULL,
  ESTADO      VARCHAR(20)   DEFAULT 'REGISTRADA' NOT NULL,
  OBSERVACION VARCHAR(500) ,
  CONSTRAINT PK_VENTA PRIMARY KEY (ID_VENTA)
);

CREATE SEQUENCE SEQ_VENTA
START WITH 1
INCREMENT BY 1;

CREATE OR REPLACE TRIGGER SEQ_TRG_VENTA
BEFORE INSERT ON VENTA
REFERENCING NEW AS NEW FOR EACH ROW
BEGIN
  SELECT SEQ_VENTA.NEXTVAL
  INTO :NEW.ID_VENTA
  FROM DUAL;
END;
/

ALTER TABLE VENTA
  ADD CONSTRAINT FK_USUARIO_TO_VENTA
    FOREIGN KEY (COD_USU)
    REFERENCES USUARIO (COD_USU);

ALTER TABLE DETALLE_VENTA
  ADD CONSTRAINT FK_VENTA_TO_DETALLE_VENTA
    FOREIGN KEY (ID_VENTA)
    REFERENCES VENTA (ID_VENTA);

ALTER TABLE DETALLE_VENTA
  ADD CONSTRAINT FK_PRODUCTO_TO_DETALLE_VENTA
    FOREIGN KEY (ID_PRO)
    REFERENCES PRODUCTO (PRO);

CREATE INDEX IDX_VENTA_FECHA
  ON VENTA (FECHA ASC);
