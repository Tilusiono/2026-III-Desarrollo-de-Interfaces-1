
CREATE TABLE DETALLE_VENTA
(
  ID_VENTA    INT           NOT NULL,
  ID_PRO      INT           NOT NULL,
  CANTIDAD    INT           NOT NULL,
  PRECIO      DECIMAL(12,2) NOT NULL,
  DESCUENTO   DECIMAL(12,2) NOT NULL DEFAULT 0,
  IMPORTE     DECIMAL(12,2),
  OBSERVACION VARCHAR(500) ,
  CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_VENTA, ID_PRO)
)
GO

CREATE TABLE PRODUCTO
(
  PRO          INT           IDENTITY(1,1),
  NOM          VARCHAR(100)  NOT NULL,
  PREC         DECIMAL(12,2) NOT NULL,
  DESCRIPCION  VARCHAR(500) ,
  STOCK        INT           NOT NULL DEFAULT 0,
  PESO_KG      DOUBLE       ,
  CALIFICACION FLOAT        ,
  ACTIVO       BOOLEAN       NOT NULL DEFAULT TRUE,
  FOTO_URL     VARCHAR(500) ,
  CONSTRAINT PK_PRODUCTO PRIMARY KEY (PRO)
)
GO

CREATE TABLE USUARIO
(
  COD_USU          INT          IDENTITY(1,1),
  NOM              VARCHAR(100) NOT NULL,
  APE              VARCHAR(100) NOT NULL,
  CORREO           VARCHAR(150) NOT NULL,
  FECHA_NACIMIENTO DATE        ,
  ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
  FECHA_REGISTRO   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_USUARIO PRIMARY KEY (COD_USU)
)
GO

ALTER TABLE USUARIO
  ADD CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO)
GO

CREATE TABLE VENTA
(
  ID_VENTA    INT           IDENTITY(1,1),
  FECHA       DATE          NOT NULL,
  COD_USU     INT           NOT NULL,
  TOTAL       DECIMAL(12,2) NOT NULL DEFAULT 0,
  HORA        TIME          NOT NULL,
  SUBTOTAL    DECIMAL(12,2) NOT NULL DEFAULT 0,
  DESCUENTO   DECIMAL(12,2) NOT NULL DEFAULT 0,
  IMPUESTO    DECIMAL(12,2) NOT NULL DEFAULT 0,
  ESTADO      VARCHAR(20)   NOT NULL DEFAULT 'REGISTRADA',
  OBSERVACION VARCHAR(500) ,
  CONSTRAINT PK_VENTA PRIMARY KEY (ID_VENTA)
)
GO

ALTER TABLE VENTA
  ADD CONSTRAINT FK_USUARIO_TO_VENTA
    FOREIGN KEY (COD_USU)
    REFERENCES USUARIO (COD_USU)
GO

ALTER TABLE DETALLE_VENTA
  ADD CONSTRAINT FK_VENTA_TO_DETALLE_VENTA
    FOREIGN KEY (ID_VENTA)
    REFERENCES VENTA (ID_VENTA)
GO

ALTER TABLE DETALLE_VENTA
  ADD CONSTRAINT FK_PRODUCTO_TO_DETALLE_VENTA
    FOREIGN KEY (ID_PRO)
    REFERENCES PRODUCTO (PRO)
GO

CREATE INDEX IDX_VENTA_FECHA
  ON VENTA (FECHA ASC)
GO
